// src/codegen/emit-java-docs.ts
import { fileSlug, type ClasspathEntry } from '../java/classpath.js';
import type { JavaLink } from '../java/inventory.js';
import type { JavaEntryRecord, JavaFileRecord, JavaManifest } from '../java/manifest.js';
import { redactUrl } from '../util/url.js';
import { DOC_MARKER, docHref, PRIVATE_NOTICE } from './docs-writer.js';

export const LICENCE_LINE = 'Only download or decompile code you are licensed to; vendor code may be covered by terms that prohibit decompiling it.';

export interface JavaDocsInput {
  version: string;
  /** Dotted class names per JAR or classes folder, keyed by `JavaFileRecord.local`. */
  classes: ReadonlyMap<string, string[]>;
  /** Command links by command key. */
  links: ReadonlyMap<string, JavaLink>;
  /** Command key to display name. */
  commandNames: ReadonlyMap<string, string>;
  /** Relative href from `entries/<component>/<file>.md` to a command doc, or undefined for a command without one. */
  commandHref?: (key: string) => string | undefined;
}

const VALID_CLASS_NAME = /^[A-Za-z_$][A-Za-z0-9_$]*(\.[A-Za-z_$][A-Za-z0-9_$]*)*$/;

const compare = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);
const oneLine = (text: string): string => text.replace(/\s+/g, ' ').trim();

/** Inline code that survives any backticks in `text`: the fence is longer than the longest run inside. */
export function codeSpan(text: string): string {
  const flat = oneLine(text);
  let longest = 0;
  for (const run of flat.match(/`+/g) ?? []) if (run.length > longest) longest = run.length;
  const ticks = '`'.repeat(longest + 1);
  const pad = flat.startsWith('`') || flat.endsWith('`') ? ' ' : '';
  return `${ticks}${pad}${flat}${pad}${ticks}`;
}

/** A table cell: one line, pipes escaped. */
const cell = (text: string): string => oneLine(text).split('|').join('\\|');

const plural = (n: number, one: string, many: string): string => `${n} ${n === 1 ? one : many}`;

/** A file name segment that is safe to write: anything outside `[A-Za-z0-9._+@-]` becomes `_`. */
function safeSegment(text: string): string {
  const out = [...text].map((ch) => (/[A-Za-z0-9._+@-]/.test(ch) ? ch : '_')).join('');
  return /^\.*$/.test(out) ? '_' : out;
}

interface Page {
  entry: JavaEntryRecord;
  file?: JavaFileRecord;
  path: string;
}

function pagesOf(manifest: JavaManifest): Page[] {
  const taken = new Set<string>();
  const pages: Page[] = [];
  const claim = (component: string, slug: string): string => {
    const base = `entries/${safeSegment(component)}/${safeSegment(slug)}`;
    let path = `${base}.md`;
    for (let n = 2; taken.has(path); n++) path = `${base}-${n}.md`;
    taken.add(path);
    return path;
  };
  for (const entry of manifest.entries) {
    if (entry.files.length === 0) {
      pages.push({ entry, path: claim(entry.component, entry.slug) });
      continue;
    }
    for (const file of entry.files) {
      // fileSlug reads only `type` and `slug`.
      const slug = fileSlug(entry as unknown as ClasspathEntry, file.path, manifest.os);
      pages.push({ entry, file, path: claim(entry.component, slug) });
    }
  }
  return pages;
}

function groupByPackage(names: string[]): Array<[string, string[]]> {
  const groups = new Map<string, string[]>();
  for (const name of names) {
    const dot = name.lastIndexOf('.');
    const pkg = dot < 0 ? '(default package)' : name.slice(0, dot);
    const list = groups.get(pkg) ?? [];
    list.push(dot < 0 ? name : name.slice(dot + 1));
    groups.set(pkg, list);
  }
  return [...groups].sort(([a], [b]) => compare(a, b)).map(([pkg, list]) => [pkg, list.sort(compare)]);
}

function readme(marker: string): string {
  return [
    marker,
    PRIVATE_NOTICE,
    LICENCE_LINE,
    '',
    '# Java classpath (for coding agents)',
    '',
    'This folder describes the Java classpath of the MOCA server, generated by `mocakit generate`.',
    '',
    '- `INDEX.md` lists every classpath entry in classpath order, with its kind, version, class count and the commands it implements.',
    '- `entries/<component>/<file>.md` lists the packages and classes of one JAR or classes folder, the commands it implements, and the classes it overrides or that override it.',
    '- `jars/` and `classes/` hold the downloaded files; `src/` holds Java source decompiled from custom code, when a decompiler is configured.',
    '- Each command page in the commands docs links to the entry and source file that implement its Java class.',
    '',
    '`execute os command` runs as the server\'s OS user. mocakit only reads: it lists directories, reads files and computes checksums, and never writes on the server.',
    '',
    'Keep `jars/` and `classes/` out of git: they are large binary files that can be downloaded again by running `mocakit generate`.',
    '',
  ].join('\n');
}

export function emitJavaDocs(manifest: JavaManifest, input: JavaDocsInput): Map<string, string> {
  const marker = `${DOC_MARKER} ${input.version} from ${redactUrl(manifest.server)}. Do not edit; regenerate with \`mocakit generate\`. -->`;
  const pages = pagesOf(manifest);
  const pagesOfEntry = new Map<string, Page[]>();
  for (const page of pages) pagesOfEntry.set(page.entry.path, [...(pagesOfEntry.get(page.entry.path) ?? []), page]);
  const firstPage = (entryPath: string): string | undefined => pagesOfEntry.get(entryPath)?.[0]?.path;

  const linksOfEntry = (entryPath: string): Array<[string, JavaLink]> =>
    [...input.links]
      .filter(([, link]) => link.kind !== 'unknown' && link.entry === entryPath)
      .sort(([ka, a], [kb, b]) => compare(input.commandNames.get(ka) ?? ka, input.commandNames.get(kb) ?? kb) || compare(a.className, b.className));

  const files = new Map<string, string>();
  files.set('README.md', readme(marker));

  // INDEX
  const index = [marker, PRIVATE_NOTICE, LICENCE_LINE, '', '# Java classpath entries', ''];
  index.push('| index | entry | selected | kind | version | classes | linked commands |', '|---|---|---|---|---|---|---|');
  for (const entry of manifest.entries) {
    const entryPages = pagesOfEntry.get(entry.path) ?? [];
    const label = codeSpan(entry.path);
    const entryCell =
      entryPages.length === 1
        ? `[${label}](${docHref(entryPages[0].path)})`
        : `${label} (${entryPages.map((p, i) => `[${i + 1}](${docHref(p.path)})`).join(', ')})`;
    const versions = [...new Set(entry.files.map((f) => f.version).filter((v): v is string => v !== undefined))].sort(compare);
    let classes: string;
    if (entry.missing) classes = 'missing on the server';
    else if (entry.files.length === 0) classes = 'not downloaded';
    else if (entry.files.some((f) => !f.readable)) classes = 'classes unknown';
    else classes = String(entry.files.reduce((sum, f) => sum + f.classes, 0));
    index.push(
      `| ${entry.index} | ${cell(entryCell)} | ${entry.selected ? 'yes' : 'no'} | ${entry.kind ?? ''} | ${cell(versions.join(', '))} | ${classes} | ${linksOfEntry(entry.path).length} |`,
    );
  }
  index.push('', '## Overridden classes', '');
  const overridden = manifest.overridden.filter((o) => VALID_CLASS_NAME.test(o.className)).sort((a, b) => compare(a.className, b.className));
  const droppedOverrides = manifest.overridden.length - overridden.length;
  /** `fromEntryPage`: the link is written on an `entries/<component>/` page rather than on INDEX.md. */
  const entryRef = (path: string, fromEntryPage: boolean): string => {
    const page = firstPage(path);
    if (page === undefined) return codeSpan(path);
    return `[${codeSpan(path)}](${docHref(fromEntryPage ? `../${page.slice('entries/'.length)}` : page)})`;
  };
  if (overridden.length === 0) index.push('None.', '');
  else {
    index.push('The first entry on the classpath wins; the others are shadowed.', '', '| class | winner | overridden entries |', '|---|---|---|');
    for (const o of overridden) {
      index.push(`| ${cell(codeSpan(o.className))} | ${cell(entryRef(o.winner, false))} | ${cell(o.losers.map((l) => entryRef(l, false)).join(', '))} |`);
    }
    index.push('');
  }
  if (droppedOverrides > 0) index.push(`${plural(droppedOverrides, 'class name was', 'class names were')} dropped because it is not a valid Java class name.`, '');
  files.set('INDEX.md', index.join('\n'));

  // Entry pages
  for (const page of [...pages].sort((a, b) => compare(a.path, b.path))) {
    const { entry, file } = page;
    const lines = [marker, `# ${codeSpan(entry.path)}`, ''];
    lines.push(`- Component: ${codeSpan(entry.component)}`, `- Classpath index: ${entry.index}`, `- Selected: ${entry.selected ? 'yes' : 'no'}`);
    if (entry.kind !== undefined) lines.push(`- Kind: ${entry.kind}`);
    if (file !== undefined) {
      lines.push(`- File: ${codeSpan(file.path)}`, `- Local copy: ${codeSpan(file.local)}`);
      if (file.maven !== undefined) lines.push(`- Maven: ${codeSpan(file.maven)}`);
      if (file.version !== undefined) lines.push(`- Version: ${codeSpan(file.version)}`);
    }
    lines.push('');
    if (entry.missing) lines.push('This entry is missing on the server.', '');
    else if (file === undefined) lines.push('Not downloaded (outside the selected roots, or no files were found).', '');

    const raw = file === undefined || !file.readable ? undefined : input.classes.get(file.local);
    let known: Set<string> | undefined;
    if (file !== undefined) {
      lines.push('## Classes', '');
      if (raw === undefined) lines.push('classes unknown', '');
      else {
        const valid = [...new Set(raw.filter((n) => VALID_CLASS_NAME.test(n)))];
        known = new Set(valid);
        const dropped = new Set(raw).size - valid.length;
        lines.push(`${plural(valid.length, 'class', 'classes')}.`, '');
        for (const [pkg, names] of groupByPackage(valid)) lines.push(`- ${codeSpan(pkg)}: ${names.map(codeSpan).join(', ')}`);
        if (valid.length > 0) lines.push('');
        if (dropped > 0) lines.push(`${plural(dropped, 'class name was', 'class names were')} dropped because it is not a valid Java class name.`, '');
      }
    }

    const links = linksOfEntry(entry.path).filter(([, link]) => known === undefined || known.has(link.className));
    lines.push('## Implemented commands', '');
    if (links.length === 0) lines.push('None.', '');
    else {
      for (const [key, link] of links) {
        const name = input.commandNames.get(key) ?? key;
        const href = input.commandHref?.(key);
        const shown = href === undefined ? codeSpan(name) : `[${codeSpan(name)}](${docHref(href)})`;
        lines.push(`- ${shown}: ${codeSpan([link.className, link.method].filter(Boolean).join('.'))}`);
      }
      lines.push('');
    }

    const wins = manifest.overridden.filter((o) => o.winner === entry.path && VALID_CLASS_NAME.test(o.className)).sort((a, b) => compare(a.className, b.className));
    const loses = manifest.overridden.filter((o) => o.losers.includes(entry.path) && VALID_CLASS_NAME.test(o.className)).sort((a, b) => compare(a.className, b.className));
    if (wins.length > 0) {
      lines.push('## Overrides', '', 'These classes are also in later entries, which they shadow.', '');
      for (const o of wins) lines.push(`- ${codeSpan(o.className)}: also in ${o.losers.map((l) => entryRef(l, true)).join(', ')}`);
      lines.push('');
    }
    if (loses.length > 0) {
      lines.push('## Overridden by', '', 'These classes are shadowed by an earlier entry.', '');
      for (const o of loses) lines.push(`- ${codeSpan(o.className)}: provided by ${entryRef(o.winner, true)}`);
      lines.push('');
    }
    files.set(page.path, `${lines.join('\n').replace(/\n+$/, '')}\n`);
  }
  return files;
}
